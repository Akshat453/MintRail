export interface ErrorOptions {
  code?: ErrorCode;
  param?: string | null;
  details?: Record<string, unknown>;
}

export class MintRailError extends Error {
  static defaultCode: ErrorCode = ErrorCode.INTERNAL_ERROR;
  readonly code: ErrorCode;
  readonly param: string | null;
  readonly details: Record<string, unknown>;

  constructor(message: string, opts: ErrorOptions = {}) {
    super(message);
    this.name = new.target.name;
    this.code = opts.code ?? (new.target as typeof MintRailError).defaultCode;
    this.param = opts.param ?? null;
    this.details = opts.details ?? {};
  }

  get httpStatus(): number {
    return HTTP_STATUS_BY_CODE[this.code] ?? 500;
  }

  toDict(): Record<string, unknown> {
    const body: Record<string, unknown> = { code: this.code, message: this.message };
    if (this.param !== null) body.param = this.param;
    if (Object.keys(this.details).length > 0) body.details = this.details;
    return body;
  }
}

